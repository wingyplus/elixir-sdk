/// `attr"""` heredoc with its body indented to match. Blank lines stay empty.
fn heredoc(w: *Writer, indent: usize, attr: []const u8, text: []const u8) !void {
    try pad(w, indent);
    try cat(w, &.{ attr, "\"\"\"\n" });
    var lines = std.mem.splitScalar(u8, text, '\n');
    while (lines.next()) |l| {
        if (l.len > 0) try pad(w, indent);
        var rest = l;
        while (std.mem.indexOfScalar(u8, rest, '\\')) |i| {
            try w.writeAll(rest[0 .. i + 1]);
            try w.writeByte('\\');
            rest = rest[i + 1 ..];
        }
        try cat(w, &.{ rest, "\n" });
    }
    try pad(w, indent);
    try w.writeAll("\"\"\"\n");
}
